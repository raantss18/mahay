//! The hub's few strings in English, French and Malagasy.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lang {
    En,
    Fr,
    Mg,
}

impl Lang {
    pub fn from_tag(tag: &str) -> Self {
        match tag.split(['-', '_']).next().unwrap_or_default() {
            "fr" => Lang::Fr,
            "mg" => Lang::Mg,
            _ => Lang::En,
        }
    }
}

